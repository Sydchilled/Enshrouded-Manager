// Build-time helper for the pkg-packaged .exe. pkg's own "assets" bundling
// system triggers a Node 18 runtime crash in the packaged binary
// (ERR_INVALID_ARG_TYPE in resolveMainPath) when combined with the "bin"
// field pkg needs to honor package.json's asset config — a known
// incompatibility, not something fixable from our side. Regular
// require()'d JS modules don't hit this, so instead of using pkg assets at
// all, this script walks public/ and bakes its contents into a plain JS
// module (src/embeddedPublic.js) that gets require()'d like any other file.
// Only used for the packaged build — `npm start` / plain `node server.js`
// keeps serving public/ straight off disk via express.static so day-to-day
// dev never needs a rebuild step.
const fs = require('fs');
const path = require('path');

const PUBLIC_DIR = path.join(__dirname, '..', 'public');
const OUT_FILE = path.join(__dirname, '..', 'src', 'embeddedPublic.js');

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2'
};

function walk(dir, base) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  let files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    const rel = path.join(base, entry.name).split(path.sep).join('/');
    if (entry.isDirectory()) {
      files = files.concat(walk(full, rel));
    } else {
      files.push({ full, rel });
    }
  }
  return files;
}

function build() {
  const files = walk(PUBLIC_DIR, '');
  const assets = {};
  for (const { full, rel } of files) {
    const ext = path.extname(full).toLowerCase();
    const mime = MIME_TYPES[ext] || 'application/octet-stream';
    const base64 = fs.readFileSync(full).toString('base64');
    assets['/' + rel] = { mime, base64 };
  }

  const header =
    '// AUTO-GENERATED by scripts/generate-embedded-public.js — do not edit by hand.\n' +
    "// Regenerated automatically as part of `npm run build:win`.\n" +
    'module.exports = ';
  fs.writeFileSync(OUT_FILE, header + JSON.stringify(assets) + ';\n');
  console.log(`Embedded ${files.length} file(s) from public/ into ${path.relative(process.cwd(), OUT_FILE)}`);
}

build();
